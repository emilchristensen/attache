/**
 * Agent transcripts normalised to the conversation a person had: user and
 * assistant text, in order. Tool calls, tool output, injected reminders and
 * subagent side-chains are left out; they are noise for remembering a session
 * and the place where secrets most often appear.
 */
export interface Turn {
  role: "user" | "assistant";
  text: string;
  at: string | null;
  /** When a streamed answer finished, when the Harness records it separately. */
  completedAt?: string | null;
  /**
   * The Harness's own id for the message this turn came from, for Harnesses
   * whose snapshots each hold only part of a session (OpenCode): the service
   * joins snapshots by it instead of by position.
   */
  id?: string;
}

export interface ParsedSession {
  turns: Turn[];
  title: string | null;
  cwd: string | null;
  startedAt: string | null;
  /** Why a transcript gave no turns although it was not empty: the format Attache could not read. */
  problem?: string;
}

// `attache-memory` wraps the memory Attache gives a Harness (see agents/pi-adapter.ts): never the owner's words.
const INJECTED = /<(attache-memory|system-reminder|command-name|command-message|command-args|local-command-stdout|local-command-caveat|environment_context|user_instructions|turn_aborted|user_shell_command|task-notification)>[\s\S]*?<\/\1>/g;

export function clean(text: string): string {
  return text.replace(INJECTED, "").replace(/\n{3,}/g, "\n\n").trim();
}

function textBlocks(content: unknown): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content
    .filter((b): b is { type: string; text: string } => !!b && typeof b === "object" && (b as { type?: unknown }).type === "text" && typeof (b as { text?: unknown }).text === "string")
    .map((b) => b.text)
    .join("\n");
}

function lines(raw: string): Array<Record<string, unknown>> {
  return raw.split("\n").flatMap((l) => {
    if (!l.trim()) return [];
    try {
      const v = JSON.parse(l) as unknown;
      return v && typeof v === "object" && !Array.isArray(v) ? [v as Record<string, unknown>] : [];
    } catch {
      return [];
    }
  });
}

/** Claude Code `~/.claude/projects/<project>/<session>.jsonl`. */
export function parseClaudeCode(raw: string): ParsedSession {
  const entries = lines(raw);
  const turns: Turn[] = [];
  let title: string | null = null;
  let cwd: string | null = null;
  let startedAt: string | null = null;
  for (const e of entries) {
    if (e.type === "ai-title" && typeof e.aiTitle === "string") title = e.aiTitle;
    if (e.type === "summary" && typeof e.summary === "string" && !title) title = e.summary;
    if (e.type !== "user" && e.type !== "assistant") continue;
    // Side-chains, injected meta messages, compaction summaries and background-task notices are not the conversation.
    if (e.isSidechain || e.isMeta || e.isCompactSummary || e.isVisibleInTranscriptOnly) continue;
    if ((e.origin as { kind?: unknown } | undefined)?.kind === "task-notification") continue;
    const at = typeof e.timestamp === "string" ? e.timestamp : null;
    startedAt ??= at;
    if (typeof e.cwd === "string") cwd ??= e.cwd;
    const message = e.message as { content?: unknown } | undefined;
    const text = clean(textBlocks(message?.content));
    if (!text || /^Caveat: The messages below were generated by the user while running local commands/.test(text) || /^\[Request interrupted by user[^\]]*\]$/.test(text)) continue;
    turns.push({ role: e.type, text, at });
  }
  return { turns, title, cwd, startedAt };
}

/**
 * Codex `~/.codex/sessions/YYYY/MM/DD/rollout-<time>-<session>.jsonl`. User and
 * assistant `message` items only: developer-role items are where injected
 * context (including Attache's own memory block) lands, so they are skipped.
 */
export function parseCodex(raw: string): ParsedSession {
  const turns: Turn[] = [];
  let cwd: string | null = null;
  let startedAt: string | null = null;
  for (const e of lines(raw)) {
    const p = (e.payload ?? {}) as Record<string, unknown>;
    if (e.type === "session_meta") {
      if (typeof p.cwd === "string") cwd ??= p.cwd;
      if (typeof p.timestamp === "string") startedAt ??= p.timestamp;
      continue;
    }
    if (e.type !== "response_item" || p.type !== "message" || (p.role !== "user" && p.role !== "assistant")) continue;
    const content = Array.isArray(p.content) ? p.content : [];
    const text = clean(
      content
        .filter((b): b is { type: string; text: string } => !!b && typeof b === "object" && ["input_text", "output_text"].includes(String((b as { type?: unknown }).type)) && typeof (b as { text?: unknown }).text === "string")
        .map((b) => b.text)
        .join("\n"),
    );
    if (!text) continue;
    const at = typeof e.timestamp === "string" ? e.timestamp : null;
    startedAt ??= at;
    turns.push({ role: p.role, text, at });
  }
  return { turns, title: null, cwd, startedAt };
}

/**
 * Antigravity `brain/<conversation>/.system_generated/logs/transcript(_full).jsonl`.
 * One step per line with a `source` of USER_EXPLICIT, MODEL or SYSTEM. The
 * official docs only promise the file; this line shape is from community
 * write-ups, so anything unrecognised yields no turns and the service logs it
 * instead of guessing.
 */
export function parseAntigravity(raw: string): ParsedSession {
  const turns: Turn[] = [];
  let startedAt: string | null = null;
  for (const e of lines(raw)) {
    const source = String(e.source ?? "");
    const role = source === "USER_EXPLICIT" ? "user" : source === "MODEL" ? "assistant" : null;
    if (!role) continue;
    const c = e.content;
    const text = clean(typeof c === "string" ? c : c && typeof c === "object" && typeof (c as { text?: unknown }).text === "string" ? (c as { text: string }).text : textBlocks(c));
    if (!text) continue;
    const at = typeof e.created_at === "string" ? e.created_at : null;
    startedAt ??= at;
    turns.push({ role, text, at });
  }
  return { turns, title: null, cwd: null, startedAt };
}

/** Consecutive runs of turns of at most `maxChars` each (a single longer turn is its own run). */
export function chunkTurns(turns: Turn[], maxChars: number): Turn[][] {
  return turns.reduce<Turn[][]>((parts, t) => {
    const last = parts.at(-1);
    const size = last ? last.reduce((n, x) => n + x.text.length + 16, 0) : 0;
    return last && size + t.text.length + 16 <= maxChars ? [...parts.slice(0, -1), [...last, t]] : [...parts, [t]];
  }, []);
}

/** Plain text for summarising: the most recent turns that fit in `maxChars`. */
export function renderTurns(turns: Turn[], names: { user: string; assistant: string }, maxChars: number): string {
  const out: string[] = [];
  let size = 0;
  for (let i = turns.length - 1; i >= 0; i--) {
    const t = turns[i]!;
    const line = `${t.role === "user" ? names.user : names.assistant}: ${t.text}`;
    if (size + line.length > maxChars) {
      if (!out.length) out.push(line.slice(-maxChars));
      break;
    }
    out.push(line);
    size += line.length + 2;
  }
  return out.reverse().join("\n\n");
}
